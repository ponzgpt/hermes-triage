"""Render a snapshot into a Markdown queue-health report."""

import re
from collections import Counter, defaultdict

from . import classify, dupes, metrics

# Areas a single person can usually reproduce on a laptop with one API key:
# no paid platform account, no second machine, no desktop-app build.
LOCAL_REPRO = {"comp/cli", "comp/agent", "comp/tools", "comp/cron", "comp/plugins",
               "area/config", "area/install-update", "area/sessions", "area/profiles",
               "area/compression", "tool/skills", "tool/mcp", "tool/memory", "tool/terminal"}
NEEDS_ACCOUNT = re.compile(r"^(platform/|provider/(bedrock|copilot|kimi|qwen|zai|minimax|xai)|backend/(modal|daytona))")
HAS_REPRO = re.compile(r"^#{2,3}\s*(steps to reproduce|reproduction|repro)\b", re.I | re.M)


def _pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "—"


def _h(x):
    if x is None:
        return "—"
    if x < 1:
        return f"{x * 60:.0f} min"
    return f"{x:.0f} h" if x < 48 else f"{x / 24:.1f} d"


def _title(i, n=90):
    t = i["title"].replace("|", "\\|")
    return t if len(t) <= n else t[: n - 1] + "…"


def _link(i):
    return f"[#{i['number']}]({i['url']})"


def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def effective_labels(i):
    """Maintainer labels if any exist in a family, else rule suggestions."""
    sugg = classify.suggest_labels(i)
    have = set(i["labels"])
    fams = {l.split("/")[0] for l in have if "/" in l}
    eff = set(have)
    eff |= {l for l in sugg if l.split("/")[0] not in fams}
    return eff, sugg


def render(snap, now, top=15):
    issues = snap["issues"]
    n = len(issues)
    by_num = {i["number"]: i for i in issues}
    maint = set(snap.get("maintainers", []))
    for i in issues:
        i["_eff"], i["_sugg"] = effective_labels(i)
        i["_sev"], i["_sev_why"] = classify.suggest_severity(i)
        i["_age"] = metrics.age_days(i, now)
        i["_resp"] = metrics.hours_to_first_response(i)
        i["_mresp"] = metrics.hours_to_first_response(i, maint)

    no_human = [i for i in issues if i["_resp"] is None]
    no_maint = [i for i in issues if i["_mresp"] is None]
    unlabeled = [i for i in issues if not i["labels"]]
    resp_h = [i["_resp"] for i in issues if i["_resp"] is not None]
    mresp_h = [i["_mresp"] for i in issues if i["_mresp"] is not None]
    recent = [i for i in issues if i["_age"] <= 30]
    recent_resp = [i["_resp"] for i in recent if i["_resp"] is not None]
    label_counts = Counter(l for i in issues for l in i["labels"])
    fast = sum(1 for h in mresp_h if h < 5 / 60)
    slow = [h for h in mresp_h if h >= 5 / 60]

    L = []
    L.append(f"# Queue health — {snap['repo']}")
    L.append("")
    L.append(f"Snapshot of open issues (pull requests excluded) taken {snap['fetched_at']}. "
             f"Generated by `hermes-triage`, a read-only tool: it suggests, it never labels, comments or closes. "
             f"Unofficial; not affiliated with Nous Research.")
    if n < (snap.get("total_open") or n):
        L.append(f"\n> Partial snapshot: {n} of {snap['total_open']} open issues (newest first).")
    L.append("")

    L.append("## Headline")
    L.append("")
    L.append(_table(["Measure", "Value"], [
        ["Open issues", f"{n:,}"],
        ["No response from anyone but the author (bots excluded)", f"{len(no_human):,} ({_pct(len(no_human), n)})"],
        [f"No response from a maintainer ({len(maint)} people who merge PRs)", f"{len(no_maint):,} ({_pct(len(no_maint), n)})"],
        ["Time to first human response — median / p90 (responded issues)",
         f"{_h(metrics.quantile(resp_h, .5))} / {_h(metrics.quantile(resp_h, .9))}"],
        ["Time to first maintainer response — median / p90",
         f"{_h(metrics.quantile(mresp_h, .5))} / {_h(metrics.quantile(mresp_h, .9))}"],
        ["… of which within 5 minutes (likely automated)", f"{fast} ({_pct(fast, len(mresp_h))})"],
        ["Time to first maintainer response, excluding those — median / p90",
         f"{_h(metrics.quantile(slow, .5))} / {_h(metrics.quantile(slow, .9))}"],
        ["Opened in the last 30 days", f"{len(recent):,}, of which {_pct(len(recent) - len(recent_resp), len(recent))} still unanswered"],
        ["Without any label", f"{len(unlabeled):,} ({_pct(len(unlabeled), n)})"],
        ["Labelled `needs-repro` / `awaiting-reporter`", f"{label_counts['needs-repro']} / {label_counts['awaiting-reporter']}"],
        ["Labelled `duplicate` but still open", f"{label_counts['duplicate']}"],
    ]))
    L.append("")

    L.append("## Age of the open queue")
    L.append("")
    ages = Counter(metrics.age_bucket(i["_age"]) for i in issues)
    unans = Counter(metrics.age_bucket(i["_age"]) for i in no_human)
    L.append(_table(["Age", "Open", "Unanswered"],
                    [[name, ages[name], f"{unans[name]} ({_pct(unans[name], ages[name])})"]
                     for _, name in metrics.AGE_BUCKETS]))
    L.append("")

    L.append("## By component")
    L.append("")
    L.append("Maintainer `comp/*` labels where present, rule suggestions otherwise (marked in the method note).")
    L.append("")
    comp = defaultdict(list)
    for i in issues:
        cs = [l for l in i["_eff"] if l.startswith("comp/")] or ["(none)"]
        for c in cs:
            comp[c].append(i)
    rows = []
    for c, xs in sorted(comp.items(), key=lambda kv: -len(kv[1])):
        un = sum(1 for i in xs if i["_resp"] is None)
        rows.append([f"`{c}`", len(xs), _pct(un, len(xs)),
                     f"{metrics.quantile([i['_age'] for i in xs], .5):.0f} d"])
    L.append(_table(["Component", "Open", "Unanswered", "Median age"], rows))
    L.append("")

    L.append("## By priority")
    L.append("")
    sev = defaultdict(list)
    for i in issues:
        sev[i["_sev"]].append(i)
    rows = []
    for lvl in classify.PRIORITIES:
        xs = sev.get(lvl, [])
        if not xs:
            continue
        labelled = sum(1 for i in xs if i["_sev_why"] == "maintainer label")
        un = sum(1 for i in xs if i["_mresp"] is None)
        rows.append([lvl, len(xs), labelled, len(xs) - labelled, _pct(un, len(xs))])
    L.append(_table(["Priority", "Open", "Labelled by maintainers", "Suggested by rules", "No maintainer response"], rows))
    L.append("")

    L.append("## Urgent and unanswered")
    L.append("")
    L.append("P0/P1 (labelled or suggested) with no maintainer response, oldest first.")
    L.append("")
    urgent = sorted((i for i in issues if i["_sev"] in ("P0", "P1") and i["_mresp"] is None),
                    key=lambda i: -i["_age"])
    L.append(_table(["Issue", "Priority", "Why", "Age", "Title"],
                    [[_link(i), i["_sev"], i["_sev_why"], f"{i['_age']:.0f} d", _title(i)] for i in urgent[:top]])
             if urgent else "None.")
    L.append(f"\n{len(urgent)} in total.")
    L.append("")

    L.append("## Likely duplicates")
    L.append("")
    allg, _ = dupes.clusters(issues)
    series = [g for g in allg if dupes.is_series(g, by_num)]
    groups = [g for g in allg if not dupes.is_series(g, by_num)]
    L.append(f"{len(groups)} candidate clusters covering {sum(len(g) for g in groups)} issues, filed by different "
             f"people or over time. Largest {min(top, len(groups))} below; the oldest issue in each is the natural "
             f"canonical one. Separately, {len(series)} look-alike *series* ({sum(len(g) for g in series)} issues) were "
             f"batch-filed by one author within three days — planned work, not duplicates; largest: "
             + ", ".join(f"{_link(by_num[g[-1]])} ({len(g)})" for g in series[:5]) + ".")
    L.append("")
    for g in groups[:top]:
        canon = by_num[g[-1]]
        L.append(f"- **{len(g)} issues** · canonical {_link(canon)} {_title(canon, 80)}")
        for num in g[:-1][:6]:
            L.append(f"  - {_link(by_num[num])} {_title(by_num[num], 80)}")
        if len(g) > 7:
            L.append(f"  - … and {len(g) - 7} more")
    L.append("")

    L.append("## Unlabelled: suggested labels")
    L.append("")
    newest = sorted(unlabeled, key=lambda i: i["created_at"], reverse=True)[:top]
    L.append(_table(["Issue", "Suggested", "Priority", "Title"],
                    [[_link(i), ", ".join(f"`{l}`" for l in sorted(i["_sugg"])) or "—", i["_sev"], _title(i, 70)]
                     for i in newest]))
    L.append("")

    L.append("## Good reproduction candidates")
    L.append("")
    L.append("Bugs with written reproduction steps, no maintainer response yet, in areas one person can "
             "reproduce on macOS or Linux with a single model provider. Sorted easiest first: CLI, configuration "
             "and install before agent internals, then by priority.")
    L.append("")
    cands = [i for i in issues
             if i["_mresp"] is None and HAS_REPRO.search(i["body"])
             and (i["_eff"] & LOCAL_REPRO)
             and not any(NEEDS_ACCOUNT.match(l) for l in i["_eff"])
             and "os/windows" not in i["_eff"] and "comp/desktop" not in i["_eff"]
             and ("type/bug" in i["_eff"] or "bug" in i["labels"])]
    # Easiest first: user-visible surfaces before agent internals, then priority, then newest.
    EASY = {"comp/cli": 0, "area/config": 0, "area/install-update": 0, "comp/cron": 1, "tool/skills": 1,
            "tool/mcp": 1, "comp/plugins": 1, "area/profiles": 1}
    def ease(i):
        return min((EASY.get(l, 2) for l in i["_eff"] & LOCAL_REPRO), default=2)
    cands.sort(key=lambda i: (ease(i), classify.PRIORITIES.index(i["_sev"]), i["_age"]))
    L.append(_table(["Issue", "Priority", "Area", "Age", "Title"],
                    [[_link(i), i["_sev"], ", ".join(sorted(i["_eff"] & LOCAL_REPRO)), f"{i['_age']:.0f} d", _title(i, 70)]
                     for i in cands[:top]]))
    L.append(f"\n{len(cands)} in total.")
    L.append("")

    L.append("## How far to trust the suggestions")
    L.append("")
    L.append("Agreement between the rules and labels maintainers already applied, per label family:")
    L.append("")
    ev = classify.evaluate(issues)
    L.append(_table(["Family", "Issues with a maintainer label", "Precision", "Recall"],
                    [[f"`{f}*`", s["issues"], f"{s['precision']:.0%}", f"{s['recall']:.0%}"] for f, s in ev.items()]))
    L.append("")

    L.append("## Method and limits")
    L.append("")
    L.append("- Read-only: one GraphQL query per 100 open issues. Nothing is written to GitHub.")
    L.append("- A *response* is the first comment by anyone other than the author that is not a bot; a *maintainer "
             "response* must come from someone who merged one of the last 300 merged pull requests "
             f"({', '.join(sorted(maint)) or 'none found'}), because GitHub hides org membership from outsiders. Only the first 10 comments "
             "are read, and times measure open issues only, so they say nothing about issues already closed.")
    L.append("- Labels and priorities come from transparent regular expressions over the title and the first "
             "1,500 characters of the body, plus the bug form's *Affected Component* field. Existing maintainer "
             "labels always win. P1 is only suggested on strong signals (data loss, security, cannot start).")
    L.append("- Duplicates are TF-IDF cosine matches over titles and code identifiers (threshold 0.55): "
             "candidates for a person to confirm, never to close automatically.")
    L.append("")
    return "\n".join(L)
